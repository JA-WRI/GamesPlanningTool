// 100% AI generated: helpers for E2E tests to create and remove their own database rows
// Uses `pg` directly: Playwright compiles tests to CommonJS and can't load the
// generated (ESM) Prisma client.
import crypto from 'crypto';
import { Client } from 'pg';
import { requireLocalDatabaseUrl } from './local-database';

export type TestGameWithNso = { gameId: string; nsoId: string };

// Exported so specs can insert page-specific data through the same localhost guard.
export async function withClient<T>(
  run: (client: Client) => Promise<T>,
): Promise<T> {
  // Also checked in playwright.config.ts; repeated here because these helpers write data.
  const client = new Client({ connectionString: requireLocalDatabaseUrl() });
  await client.connect();
  try {
    return await run(client);
  } finally {
    await client.end();
  }
}

// Creates an active game with one active NSO linked to it.
export async function createTestGameWithNso(): Promise<TestGameWithNso> {
  const suffix = crypto.randomUUID().slice(0, 8);
  const nsoId = crypto.randomUUID(); // UUID ids are generated by Prisma, not the DB

  return withClient(async (client) => {
    const { rows } = await client.query<{ id: number }>(
      `INSERT INTO games (name, country, city, start_date, end_date, planning_period_start, planning_period_end)
       VALUES ($1, 'Canada', 'Test City', '2030-07-01', '2030-07-15', '2029-01-01', '2030-06-01')
       RETURNING id`,
      [`E2E Game ${suffix}`],
    );
    const gameId = rows[0].id;

    await client.query(
      `INSERT INTO nsos (id, name, sport) VALUES ($1, $2, 'Testing')`,
      [nsoId, `E2E NSO ${suffix}`],
    );
    await client.query(
      `INSERT INTO game_nsos (id, game_id, nso_id) VALUES ($1, $2, $3)`,
      [crypto.randomUUID(), gameId, nsoId],
    );

    return { gameId: String(gameId), nsoId };
  });
}

// Deletes only the rows created by createTestGameWithNso.
export async function deleteTestGameWithNso({
  gameId,
  nsoId,
}: TestGameWithNso) {
  await withClient(async (client) => {
    await client.query(
      `DELETE FROM game_nsos WHERE game_id = $1 AND nso_id = $2`,
      [Number(gameId), nsoId],
    );
    await client.query(`DELETE FROM nsos WHERE id = $1`, [nsoId]);
    await client.query(`DELETE FROM games WHERE id = $1`, [Number(gameId)]);
  });
}
